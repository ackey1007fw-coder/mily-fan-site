import test from "node:test";
import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {groupByBroadcastDate, observationPoints, lastObservedValue} from "../public/data-lab/assets/daily-archive-core.js";
const read=p=>readFileSync(new URL("../"+p,import.meta.url),"utf8");
const data=JSON.parse(read("public/data-lab/data/mily-morning-20261113-aggregate.json"));
const report=read("data-lab/reports/20261113-morning/index.html");
const csv=read("public/data-lab/data/mily-morning-20261113-observations.csv");
test("2026-11-13 morning: last valid UI display is a mid-stream reference; new-event pt is a recorded difference",()=>{
  assert.equal(data.liveId,23679723);assert.equal(data.roomId,573253);
  assert.equal(data.dateJst,"2026-11-13");assert.equal(data.session,"morning");
  assert.equal(data.finalServiceValueVerified,false);assert.equal(data.quality.verified_final,false);assert.equal(data.quality.end_confirmed,false);
  assert.equal(data.lastValidOnline.confirmedFinal,false);
  assert.deepEqual({...data.metrics},{stars:22304,visits:2373,comments:1490,firstVisits:135,repeatVisits:42,newFollows:4,otherFree:716,star100People:198,recommendedCommentPeople:515});
  assert.equal(data.observations.length,140);
  assert.equal(lastObservedValue(data,"stars","2026-11-13"),22304);
  assert.equal(observationPoints(data,"stars","2026-11-13").length,140);
  assert.equal(data.quality.interpolated,false);assert.equal(data.quality.zeroFilled,false);
  assert.ok(data.observations.every(o=>o.stars>0),"post-end reset rows are excluded");
  const ev=data.eventPointObservations;
  assert.equal(ev.eventActive,true);assert.equal(ev.start.point,158136);assert.equal(ev.end.point,188675);assert.equal(ev.pointDifference,30539);
  assert.equal(ev.start.rank,2);assert.equal(ev.end.rank,2);
  assert.equal(data.commentLog.entries,670);assert.equal(data.commentLog.anonymousPosterCount,230);
  assert.equal(csv.trim().split("\n").length,141);
  assert.match(ev.note,/05:30〜06:10/);assert.match(ev.note,/補間・逆算なし/);
  assert.ok(!("gap_to_upper" in ev.start) && !("gap_to_lower" in ev.end));
});
test("2026-11-13 morning: report and JSON keep viewers anonymous and wiring is in place",()=>{
  const all=report+JSON.stringify(data)+csv;
  assert.doesNotMatch(all,/\/workspace\/|\.jsonl|user_id|avatar|viewer[_-]?id|comment_text|access_token|drive\.google|uniqueCommenters|giftPointsEst|gap_to_upper|gap_to_lower|bcsvr|SREmu|那丘|なおか/i);
  assert.match(report,/noindex,nofollow,noarchive/);
  assert.match(report,/確定合計ではありません/);assert.match(report,/途中参考値/);assert.match(report,/\+30,539pt/);
  assert.match(report,/07:25:54/);assert.match(report,/05:30〜06:10は未記録/);
  for(const o of data.observations) assert.ok(report.includes(o.atJst.slice(11,19)));
  assert.deepEqual(groupByBroadcastDate().find(g=>g.date==="2026-11-13").entries.map(x=>x.slot),["morning"]);
  assert.ok(read("vite.config.ts").includes("data-lab/reports/20261113-morning/index.html"));
  assert.match(read("data-lab/index.html"),/href="\/data-lab\/reports\/20261113-morning\/">最新の配信レポート/);
  assert.match(read("public/data-lab/assets/daily-archive-core.js"),/morning: "朝"/);
});
