import test from "node:test";
import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {groupByBroadcastDate, observationPoints, lastObservedValue} from "../public/data-lab/assets/daily-archive-core.js";
const read=p=>readFileSync(new URL("../"+p,import.meta.url),"utf8");
const data=JSON.parse(read("public/data-lab/data/mily-night-20261112-aggregate.json"));
const report=read("data-lab/reports/20261112-night/index.html");
const csv=read("public/data-lab/data/mily-night-20261112-observations.csv");
test("2026-11-12 night: last valid UI display is a mid-stream reference; new-event pt is a recorded difference",()=>{
  assert.equal(data.liveId,23678187);assert.equal(data.roomId,573253);
  assert.equal(data.dateJst,"2026-11-12");assert.equal(data.session,"night");
  assert.equal(data.finalServiceValueVerified,false);assert.equal(data.quality.verified_final,false);assert.equal(data.quality.end_confirmed,false);
  assert.equal(data.lastValidOnline.confirmedFinal,false);
  assert.deepEqual({...data.metrics},{stars:4890,visits:205,comments:937,firstVisits:7,repeatVisits:2,newFollows:1,otherFree:130,star100People:47,recommendedCommentPeople:36});
  assert.equal(data.observations.length,214);
  assert.equal(lastObservedValue(data,"stars","2026-11-12"),4890);
  assert.equal(observationPoints(data,"stars","2026-11-12").length,214);
  assert.equal(data.quality.interpolated,false);assert.equal(data.quality.zeroFilled,false);
  assert.ok(data.observations.every(o=>o.stars>0),"post-end reset rows are excluded");
  const ev=data.eventPointObservations;
  assert.equal(ev.eventActive,true);assert.equal(ev.start.point,108102);assert.equal(ev.end.point,138078);assert.equal(ev.pointDifference,29976);
  assert.equal(ev.start.rank,3);assert.equal(ev.end.rank,2);
  assert.equal(data.commentLog.entries,819);assert.equal(data.commentLog.anonymousPosterCount,67);
  assert.equal(csv.trim().split("\n").length,215);
  assert.match(ev.note,/21:31〜21:36/);assert.match(ev.note,/補間・逆算なし/);
  assert.ok(!("gap_to_upper" in ev.start) && !("gap_to_lower" in ev.end));
});
test("2026-11-12 night: report and JSON keep viewers anonymous and wiring is in place",()=>{
  const all=report+JSON.stringify(data)+csv;
  assert.doesNotMatch(all,/\/workspace\/|\.jsonl|user_id|avatar|viewer[_-]?id|comment_text|access_token|drive\.google|uniqueCommenters|giftPointsEst|gap_to_upper|gap_to_lower|bcsvr|SREmu|那丘|なおか/i);
  assert.match(report,/noindex,nofollow,noarchive/);
  assert.match(report,/確定合計ではありません/);assert.match(report,/途中参考値/);assert.match(report,/\+29,976pt/);
  assert.match(report,/23:36:30/);assert.match(report,/21:31〜21:36は未記録/);
  for(const o of data.observations) assert.ok(report.includes(o.atJst.slice(11,19)));
  assert.deepEqual(groupByBroadcastDate().find(g=>g.date==="2026-11-12").entries.map(x=>x.slot),["night"]);
  assert.ok(read("vite.config.ts").includes("data-lab/reports/20261112-night/index.html"));
  assert.match(read("data-lab/index.html"),/href="\/data-lab\/reports\/20261112-night\/">最新の配信レポート/);
  assert.match(read("public/data-lab/assets/daily-archive-core.js"),/night: "夜"/);
});
