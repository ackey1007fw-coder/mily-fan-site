import test from "node:test";
import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {groupByBroadcastDate, observationPoints, lastObservedValue} from "../public/data-lab/assets/daily-archive-core.js";
const read=p=>readFileSync(new URL("../"+p,import.meta.url),"utf8");
const data=JSON.parse(read("public/data-lab/data/mily-afternoon-20261115-aggregate.json"));
const report=read("data-lab/reports/20261115-afternoon/index.html");
const csv=read("public/data-lab/data/mily-afternoon-20261115-observations.csv");
test("2026-11-15 afternoon: API comment log aggregates only; event pt for this frame is not recorded and the outcome is the announced avatar right",()=>{
  assert.equal(data.liveId,23688974);assert.equal(data.roomId,573253);
  assert.equal(data.dateJst,"2026-11-15");assert.equal(data.session,"noon");
  assert.equal(data.finalServiceValueVerified,false);assert.equal(data.quality.verified_final,false);assert.equal(data.quality.end_confirmed,false);
  assert.equal(data.lastValidOnline,null);
  assert.deepEqual({...data.metrics},{stars:null,visits:null,comments:null,firstVisits:null,repeatVisits:null,newFollows:null,otherFree:null,star100People:null,recommendedCommentPeople:null});
  assert.equal(data.observations.length,8);
  assert.equal(lastObservedValue(data,"comments","2026-11-15"),295);
  assert.equal(observationPoints(data,"comments","2026-11-15").length,8);
  assert.equal(observationPoints(data,"stars","2026-11-15").length,0);
  assert.equal(data.quality.interpolated,false);assert.equal(data.quality.zeroFilled,false);
  assert.equal(data.quality.rawCommentLogRows,367);assert.equal(data.quality.systemAnnouncementRows,59);assert.equal(data.quality.refetchDuplicateRows,12);assert.equal(data.quality.viewerCommentRows,296);
  const ev=data.eventPointObservations;
  assert.equal(ev.eventActive,true);assert.equal(ev.start,null);assert.equal(ev.end,null);
  assert.equal(ev.lastKnownBeforeFrame.point,282152);assert.equal(ev.lastKnownBeforeFrame.rank,2);
  assert.match(ev.outcome,/アバ権/);assert.match(ev.outcome,/公式確認待ち/);
  assert.equal(data.commentLog.entries,367);assert.equal(data.commentLog.viewerEntries,296);assert.equal(data.commentLog.anonymousPosterCount,39);
  assert.equal(data.giftLog.entries,24);assert.equal(data.giftLog.totalItems,144);
  assert.equal(csv.trim().split("\n").length,9);
  assert.match(ev.note,/推測で埋めません/);
});
test("2026-11-15 afternoon: report and JSON keep viewers anonymous and wiring is in place",()=>{
  const all=report+JSON.stringify(data)+csv;
  assert.doesNotMatch(all,/\/workspace\/|\.jsonl|user_id|avatar_id|viewer[_-]?id|comment_text|access_token|drive\.google|uniqueCommenters|giftPointsEst|gap_to_upper|gap_to_lower|bcsvr|SREmu|那丘|なおか/i);
  assert.match(report,/noindex,nofollow,noarchive/);
  assert.match(report,/公式確認待ち/);assert.match(report,/アバ権/);assert.match(report,/282,152pt/);
  assert.match(report,/15:16:00/);assert.match(report,/最後の約5分間は未記録/);
  for(const o of data.observations) assert.ok(report.includes(o.atJst.slice(11,19)));
  assert.deepEqual(groupByBroadcastDate().find(g=>g.date==="2026-11-15").entries.map(x=>x.slot),["noon","morning"]);
  assert.ok(read("vite.config.ts").includes("data-lab/reports/20261115-afternoon/index.html"));
  assert.match(read("data-lab/index.html"),/href="\/data-lab\/reports\/20261115-afternoon\/">最新の配信レポート/);
  assert.match(read("public/data-lab/assets/daily-archive-core.js"),/noon: "昼"/);
  assert.doesNotMatch(report,/この配信の写真|短い映像（原音つき）/);
});
