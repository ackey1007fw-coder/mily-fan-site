import test from "node:test";
import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {groupByBroadcastDate, observationPoints, lastObservedValue} from "../public/data-lab/assets/daily-archive-core.js";
const read=p=>readFileSync(new URL("../"+p,import.meta.url),"utf8");
const data=JSON.parse(read("public/data-lab/data/mily-noon-20261114-aggregate.json"));
const report=read("data-lab/reports/20261114-noon/index.html");
const csv=read("public/data-lab/data/mily-noon-20261114-observations.csv");
test("2026-11-14 noon: last valid UI display is a mid-stream reference; new-event pt is a recorded difference",()=>{
  assert.equal(data.liveId,23684728);assert.equal(data.roomId,573253);
  assert.equal(data.dateJst,"2026-11-14");assert.equal(data.session,"noon");
  assert.equal(data.finalServiceValueVerified,false);assert.equal(data.quality.verified_final,false);assert.equal(data.quality.end_confirmed,false);
  assert.equal(data.lastValidOnline.confirmedFinal,false);
  assert.deepEqual({...data.metrics},{stars:2121,visits:152,comments:379,firstVisits:3,repeatVisits:9,newFollows:1,otherFree:120,star100People:20,recommendedCommentPeople:22});
  assert.equal(data.observations.length,68);
  assert.equal(lastObservedValue(data,"stars","2026-11-14"),2121);
  assert.equal(observationPoints(data,"stars","2026-11-14").length,68);
  assert.equal(data.quality.interpolated,false);assert.equal(data.quality.zeroFilled,false);
  assert.ok(data.observations.every(o=>o.stars>0),"post-end reset rows are excluded");
  assert.equal(data.observations.filter(o=>o.visits==null).length,9);
  const ev=data.eventPointObservations;
  assert.equal(ev.eventActive,true);assert.equal(ev.start.point,236934);assert.equal(ev.end.point,243556);assert.equal(ev.pointDifference,6622);
  assert.equal(ev.start.rank,3);assert.equal(ev.end.rank,3);
  assert.equal(data.commentLog.entries,119);assert.equal(data.commentLog.anonymousPosterCount,28);
  assert.equal(csv.trim().split("\n").length,69);
  assert.match(ev.note,/13:21〜13:22/);assert.match(ev.note,/補間・逆算なし/);
  assert.ok(!("gap_to_upper" in ev.start) && !("gap_to_lower" in ev.end));
});
test("2026-11-14 noon: report and JSON keep viewers anonymous and wiring is in place",()=>{
  const all=report+JSON.stringify(data)+csv;
  assert.doesNotMatch(all,/\/workspace\/|\.jsonl|user_id|avatar|viewer[_-]?id|comment_text|access_token|drive\.google|uniqueCommenters|giftPointsEst|gap_to_upper|gap_to_lower|bcsvr|SREmu|那丘|なおか/i);
  assert.match(report,/noindex,nofollow,noarchive/);
  assert.match(report,/確定合計ではありません/);assert.match(report,/途中参考値/);assert.match(report,/\+6,622pt/);
  assert.match(report,/14:12:11/);assert.match(report,/13:21〜13:22は未記録/);
  for(const o of data.observations) assert.ok(report.includes(o.atJst.slice(11,19)));
  assert.deepEqual(groupByBroadcastDate().find(g=>g.date==="2026-11-14").entries.map(x=>x.slot),["noon","morning"]);
  assert.ok(read("vite.config.ts").includes("data-lab/reports/20261114-noon/index.html"));
  assert.match(read("data-lab/index.html"),/href="\/data-lab\/reports\/20261114-noon\/">最新の配信レポート/);
  assert.match(read("public/data-lab/assets/daily-archive-core.js"),/noon: "昼"/);
  assert.doesNotMatch(report,/この配信の写真|短い映像（原音つき）/);
});
