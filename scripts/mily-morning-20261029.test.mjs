import test from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {streamRecaps} from '../src/data/streamRecaps.ts';
import {DAILY_STREAM_ENTRIES,observationPoints,lastObservedValue} from '../public/data-lab/assets/daily-archive-core.js';
test('October 29 morning separates memo clocks, star samples, references and loss',()=>{
const r=streamRecaps.find(r=>r.id==='2026-10-29-morning-showroom');
assert.equal(streamRecaps[0],r);assert.equal(r.timestampBasis,'memo-clock');
assert.equal(r.highlights.length,6);assert.deepEqual(r.timeline,[]);assert.equal(r.songs,undefined);assert.equal(r.image,undefined);assert.equal(r.nextNote,'');
assert.match(r.transcriptionNote,/原音・映像の再確認は行っていません/);
const d=JSON.parse(readFileSync('public/data-lab/data/mily-morning-20261029-aggregate.json'));
assert.equal(d.liveId,23616187);
assert.deepEqual(Object.values(d.referenceSnapshot.metrics),[21,25,649,319,2,4665,6170,43,48]);
assert.ok(Object.values(d.metrics).every(v=>v===null));
for(const flag of ['finalServiceValueVerified','completeCoverageConfirmed','timingComparisonEligible']) assert.equal(d[flag],false);
assert.equal(d.referenceSnapshot.savedObservedAtJst,'2026-10-29T06:34:16.126+09:00');
assert.equal(d.referenceSnapshot.lastScreenProgressAtJst,'2026-10-29T06:32:47.154+09:00');
assert.equal(d.collectionQuality.collectorFinished,true);assert.equal(d.collectionQuality.savedFrames,1521);
assert.equal(d.collectionQuality.domDroppedFragments,189627);assert.equal(d.collectionQuality.rawComplete,false);
const pts=d.starTrendReference.points;assert.equal(pts.length,8);
assert.equal(pts.at(-1).stars-pts[0].stars,4545);assert.equal(pts.at(-1).star100People-pts[0].star100People,42);
assert.equal(Math.max(...pts.slice(1).map((p,i)=>p.stars-pts[i].stars)),1074);
assert.equal(d.collectionQuality.maxGapSeconds,43.002);
assert.deepEqual(observationPoints(d,'stars',d.dateJst),[]);assert.equal(lastObservedValue(d,'stars',d.dateJst),4665);
assert.equal(DAILY_STREAM_ENTRIES.filter(e=>e.file==='mily-morning-20261029-aggregate.json').length,1);
const html=readFileSync('data-lab/reports/20261029-morning/index.html','utf8');
assert.match(html,/noindex,nofollow,noarchive/);assert.match(html,/1,074/);assert.match(html,/1,521/);
assert.doesNotMatch(JSON.stringify(r)+html+JSON.stringify(d),/10:15|3,673|あっきー|drive\.google|\.jsonl|C:\\Users|大学/);
assert.match(readFileSync('vite.config.ts','utf8'),/dataLabMorning20261029/);
});
