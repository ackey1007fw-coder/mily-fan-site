import test from "node:test";
import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {groupByBroadcastDate, observationPoints, lastObservedValue} from "../public/data-lab/assets/daily-archive-core.js";
const read=p=>readFileSync(new URL("../"+p,import.meta.url),"utf8");
const data=JSON.parse(read("public/data-lab/data/mily-night-20261114-aggregate.json"));
const report=read("data-lab/reports/20261114-night/index.html");
const csv=read("public/data-lab/data/mily-night-20261114-observations.csv");
test("2026-11-14 night: last valid UI display is a mid-stream reference; new-event pt is a recorded difference",()=>{
  assert.equal(data.liveId,23686830);assert.equal(data.roomId,573253);
  assert.equal(data.dateJst,"2026-11-14");assert.equal(data.session,"night");
  assert.equal(data.finalServiceValueVerified,false);assert.equal(data.quality.verified_final,false);assert.equal(data.quality.end_confirmed,false);
  assert.equal(data.lastValidOnline.confirmedFinal,false);
  assert.deepEqual({...data.metrics},{stars:2620,visits:92,comments:436,firstVisits:0,repeatVisits:0,newFollows:0,otherFree:80,star100People:25,recommendedCommentPeople:18});
  assert.equal(data.observations.length,135);
  assert.equal(lastObservedValue(data,"stars","2026-11-14"),2620);
  assert.equal(observationPoints(data,"stars","2026-11-14").length,135);
  assert.equal(data.quality.interpolated,false);assert.equal(data.quality.zeroFilled,false);
  assert.ok(data.observations.every(o=>o.stars>0),"post-end reset rows are excluded");
  assert.equal(data.quality.visitsNulledRows,0);
  const ev=data.eventPointObservations;
  assert.equal(ev.eventActive,true);assert.equal(ev.start.point,244696);assert.equal(ev.end.point,257309);assert.equal(ev.pointDifference,12613);
  assert.equal(ev.start.rank,3);assert.equal(ev.end.rank,3);
  assert.equal(data.commentLog.entries,309);assert.equal(data.commentLog.anonymousPosterCount,27);
  assert.equal(csv.trim().split("\n").length,136);
  assert.match(ev.note,/22:40〜22:44/);assert.match(ev.note,/補間・逆算なし/);
  assert.ok(!("gap_to_upper" in ev.start) && !("gap_to_lower" in ev.end));
});
test("2026-11-14 night: report and JSON keep viewers anonymous and wiring is in place",()=>{
  const all=report+JSON.stringify(data)+csv;
  assert.doesNotMatch(all,/\/workspace\/|\.jsonl|user_id|avatar|viewer[_-]?id|comment_text|access_token|drive\.google|uniqueCommenters|giftPointsEst|gap_to_upper|gap_to_lower|bcsvr|SREmu|那丘|なおか/i);
  assert.match(report,/noindex,nofollow,noarchive/);
  assert.match(report,/確定合計ではありません/);assert.match(report,/途中参考値/);assert.match(report,/\+12,613pt/);
  assert.match(report,/23:37:04/);assert.match(report,/22:40〜22:44は未記録/);
  for(const o of data.observations) assert.ok(report.includes(o.atJst.slice(11,19)));
  assert.deepEqual(groupByBroadcastDate().find(g=>g.date==="2026-11-14").entries.map(x=>x.slot),["night","morning"]);
  assert.ok(read("vite.config.ts").includes("data-lab/reports/20261114-night/index.html"));
  assert.match(read("data-lab/index.html"),/href="\/data-lab\/reports\/20261114-night\/">最新の配信レポート/);
  assert.match(read("public/data-lab/assets/daily-archive-core.js"),/night: "夜"/);
  assert.doesNotMatch(report,/この配信の写真|短い映像（原音つき）/);
});
