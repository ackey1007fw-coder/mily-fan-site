import test from "node:test";
import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {groupByBroadcastDate, observationPoints, lastObservedValue} from "../public/data-lab/assets/daily-archive-core.js";
const read=p=>readFileSync(new URL("../"+p,import.meta.url),"utf8");
const data=JSON.parse(read("public/data-lab/data/mily-morning-20261111-aggregate.json"));
const report=read("data-lab/reports/20261111-morning/index.html");
const csv=read("public/data-lab/data/mily-morning-20261111-observations.csv");
test("2026-11-11 morning: last valid UI display is a mid-stream reference; new-event pt is a recorded difference",()=>{
  assert.equal(data.liveId,23671695);assert.equal(data.roomId,573253);
  assert.equal(data.dateJst,"2026-11-11");assert.equal(data.session,"morning");
  assert.equal(data.finalServiceValueVerified,false);assert.equal(data.quality.verified_final,false);assert.equal(data.quality.end_confirmed,false);
  assert.equal(data.lastValidOnline.confirmedFinal,false);
  assert.deepEqual({...data.metrics},{stars:8816,visits:1240,comments:712,firstVisits:110,repeatVisits:46,newFollows:4,otherFree:252,star100People:78,recommendedCommentPeople:112});
  assert.equal(data.observations.length,271);
  assert.equal(lastObservedValue(data,"stars","2026-11-11"),8816);
  assert.equal(observationPoints(data,"stars","2026-11-11").length,271);
  assert.equal(data.quality.interpolated,false);assert.equal(data.quality.zeroFilled,false);
  assert.ok(data.observations.every(o=>o.stars>0),"post-end reset rows are excluded");
  const ev=data.eventPointObservations;
  assert.equal(ev.eventActive,true);assert.equal(ev.start.point,7748);assert.equal(ev.end.point,57562);assert.equal(ev.pointDifference,49814);
  assert.equal(ev.start.rank,5);assert.equal(ev.end.rank,2);
  assert.equal(data.commentLog.entries,564);assert.equal(data.commentLog.anonymousPosterCount,118);
  assert.equal(csv.trim().split("\n").length,272);
  assert.match(ev.note,/06:59〜07:11/);assert.match(ev.note,/補間・逆算なし/);
});
