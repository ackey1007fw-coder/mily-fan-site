import test from "node:test";
import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {groupByBroadcastDate, observationPoints, lastObservedValue} from "../public/data-lab/assets/daily-archive-core.js";
const read=p=>readFileSync(new URL("../"+p,import.meta.url),"utf8");
const data=JSON.parse(read("public/data-lab/data/mily-morning-20261112-aggregate.json"));
const report=read("data-lab/reports/20261112-morning/index.html");
const csv=read("public/data-lab/data/mily-morning-20261112-observations.csv");
test("2026-11-12 morning: last valid UI display is a mid-stream reference; new-event pt is a recorded difference",()=>{
  assert.equal(data.liveId,23675715);assert.equal(data.roomId,573253);
  assert.equal(data.dateJst,"2026-11-12");assert.equal(data.session,"morning");
  assert.equal(data.finalServiceValueVerified,false);assert.equal(data.quality.verified_final,false);assert.equal(data.quality.end_confirmed,false);
  assert.equal(data.lastValidOnline.confirmedFinal,false);
  assert.deepEqual({...data.metrics},{stars:2431,visits:336,comments:233,firstVisits:7,repeatVisits:9,newFollows:3,otherFree:11,star100People:22,recommendedCommentPeople:27});
  assert.equal(data.observations.length,66);
  assert.equal(lastObservedValue(data,"stars","2026-11-12"),2431);
  assert.equal(observationPoints(data,"stars","2026-11-12").length,66);
  assert.equal(data.quality.interpolated,false);assert.equal(data.quality.zeroFilled,false);
  assert.ok(data.observations.every(o=>o.stars>0),"post-end reset rows are excluded");
  const ev=data.eventPointObservations;
  assert.equal(ev.eventActive,true);assert.equal(ev.start.point,104132);assert.equal(ev.end.point,107264);assert.equal(ev.pointDifference,3132);
  assert.equal(ev.start.rank,2);assert.equal(ev.end.rank,2);
  assert.equal(data.commentLog.entries,268);assert.equal(data.commentLog.anonymousPosterCount,45);
  assert.equal(data.commentLog.sources[0].count,318);
  assert.equal(data.commentLog.sources[1].count,265);
  assert.equal(data.commentLog.sources[2].count,268);
  assert.equal(csv.trim().split("\n").length,67);
  assert.match(ev.note,/06:07〜06:12/);assert.match(ev.note,/補間・逆算なし/);
});
