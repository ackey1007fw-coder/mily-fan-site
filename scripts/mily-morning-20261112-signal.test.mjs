  const all=report+JSON.stringify(data)+csv;
  assert.doesNotMatch(all,/\/workspace\/|\.jsonl|user_id|avatar|viewer[_-]?id|comment_text|access_token|drive\.google|uniqueCommenters|giftPointsEst|gap_to_upper|gap_to_lower|bcsvr|SREmu|那丘|なおか|むぎ/i);
  assert.match(report,/noindex,nofollow,noarchive/);
  assert.match(report,/確定合計ではありません/);assert.match(report,/途中参考値/);
  assert.match(report,/\+3,132pt/);
  assert.match(report,/06:33:05/);
  assert.match(report,/06:07〜06:12は未記録/);
  assert.match(report,/318/);assert.match(report,/265/);assert.match(report,/268/);
  assert.match(report,/543/);
