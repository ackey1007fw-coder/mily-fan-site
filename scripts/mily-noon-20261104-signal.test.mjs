  assert.equal(data.observations.length,13);
  assert.equal(lastObservedValue(data,"stars","2026-11-04"),3862);
  assert.equal(observationPoints(data,"stars","2026-11-04").length,13);
  assert.equal(data.quality.interpolated,false);assert.equal(data.quality.zeroFilled,false);
  assert.equal(data.quality.sourceReconciliation.otherSeriesMerged,false);
