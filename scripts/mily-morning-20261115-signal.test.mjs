import test from "node:test";
import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {groupByBroadcastDate, observationPoints, lastObservedValue} from "../public/data-lab/assets/daily-archive-core.js";
const read=p=>readFileSync(new URL("../"+p,import.meta.url),"utf8");
const data=JSON.parse(read("public/data-lab/data/mily-morning-20261115-aggregate.json"));
const report=read("data-lab/reports/20261115-morning/index.html");
const csv=read("public/data-lab/data/mily-morning-20261115-observations.csv");
test("2026-11-15 morning: last valid UI display is a mid-stream reference; new-event pt is a recorded difference",()=>{
  assert.equal(data.liveId,23687917);assert.equal(data.roomId,573253);
  assert.equal(data.dateJst,"2026-11-15");assert.equal(data.session,"morning");
  assert.equal(data.finalServiceValueVerified,false);assert.equal(data.quality.verified_final,false);assert.equal(data.quality.end_confirmed,false);
  assert.equal(data.lastValidOnline.confirmedFinal,false);
  assert.deepEqual({...data.metrics},{stars:1254,visits:199,comments:204,firstVisits:1,repeatVisits:8,newFollows:0,otherFree:110,star100People:11,recommendedCommentPeople:21});
  assert.equal(data.observations.length,41);
  assert.equal(lastObservedValue(data,"stars","2026-11-15"),1254);
  assert.equal(observationPoints(data,"stars","2026-11-15").length,41);
  assert.equal(data.quality.interpolated,false);assert.equal(data.quality.zeroFilled,false);
  assert.ok(data.observations.every(o=>o.stars>0),"post-end reset rows are excluded");
  assert.equal(data.quality.visitsNulledRows,9);
  assert.equal(data.quality.broadcastStyle,"radio");
  const ev=data.eventPointObservations;
  assert.equal(ev.eventActive,true);assert.equal(ev.start.point,272543);assert.equal(ev.end.point,282152);assert.equal(ev.pointDifference,9609);
  assert.equal(ev.start.rank,2);assert.equal(ev.end.rank,2);
  assert.equal(data.commentLog.entries,149);assert.equal(data.commentLog.anonymousPosterCount,24);
  assert.equal(csv.trim().split("\n").length,42);
  assert.match(ev.note,/06:03〜06:06/);assert.match(ev.note,/補間・逆算なし/);
  assert.ok(!("gap_to_upper" in ev.start) && !("gap_to_lower" in ev.end));
});
test("2026-11-15 morning: report and JSON keep viewers anonymous and wiring is in place",()=>{
  const all=report+JSON.stringify(data)+csv;
  assert.doesNotMatch(all,/\/workspace\/|\.jsonl|user_id|avatar|viewer[_-]?id|comment_text|access_token|drive\.google|uniqueCommenters|giftPointsEst|gap_to_upper|gap_to_lower|bcsvr|SREmu|那丘|なおか/i);
  assert.match(report,/noindex,nofollow,noarchive/);
  assert.match(report,/確定合計ではありません/);assert.match(report,/途中参考値/);assert.match(report,/\+9,609pt/);
  assert.match(report,/06:24:50/);assert.match(report,/06:03〜06:06は未記録/);
  assert.match(report,/ラジオ形式/);
  for(const o of data.observations) assert.ok(report.includes(o.atJst.slice(11,19)));
  assert.deepEqual(groupByBroadcastDate().find(g=>g.date==="2026-11-15").entries.map(x=>x.slot),["night","noon","morning"]);
  assert.deepEqual(groupByBroadcastDate().find(g=>g.date==="2026-11-14").entries.map(x=>x.slot),["night","noon","morning"]);
  assert.ok(read("vite.config.ts").includes("data-lab/reports/20261115-morning/index.html"));
  assert.match(read("data-lab/index.html"),/href="\/data-lab\/reports\/20261115-night\/">最新の配信レポート/);
  assert.match(read("public/data-lab/assets/daily-archive-core.js"),/morning: "朝"/);
  assert.doesNotMatch(report,/この配信の写真|短い映像（原音つき）/);
});
